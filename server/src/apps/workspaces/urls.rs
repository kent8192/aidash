//! Application endpoint registration and access policies.
use super::views::{channels, duties, duty_events, management, scratch};
use crate::apps::identity::services::boundary::AccessBoundary;
use reinhardt::UnifiedRouter;

use crate::apps::drives::views as drives;

pub fn url_patterns() -> UnifiedRouter {
	UnifiedRouter::new().server(|server| {
		server
			.endpoint(drives::browse)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(drives::download)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(drives::mutation)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(drives::upload_start)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(drives::upload_part)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(drives::upload_commit)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(duties::thread_list)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(duties::create)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(duties::list)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(duties::notices)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(duties::read)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(duties::update)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(duties::pause)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(duties::resume)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(duties::successor)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(duties::take_over)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(duties::run_now)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(duties::remove)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(duty_events::list)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(duty_events::create)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(duty_events::remove)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(duty_events::events)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			// A webhook authenticates by the signature of its body (#1011).
			.endpoint(duty_events::webhook)
			.with_route_middleware(AccessBoundary::public())
			// Another Node authenticates with its Federation token (#1013).
			.endpoint(duty_events::node_event)
			.with_route_middleware(AccessBoundary::peer().with_visibility())
			.endpoint(scratch::create)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(scratch::list)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(scratch::limits)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(scratch::read)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(scratch::settings)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(scratch::add_member)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(scratch::remove_member)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(scratch::clear)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(scratch::clear_thread)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(scratch::remove)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(management::task_list)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(management::thread_list)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(management::thread_create)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(management::thread_get)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(management::thread_update)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(management::task_goal)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(management::task_goal_change)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(management::task_create)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(management::message_create)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(management::task_abandon)
			.with_route_middleware(
				AccessBoundary::authenticated()
					.with_visibility()
					.stops_work(),
			)
			.endpoint(channels::channel_message_create)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(channels::channel_message_history)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(channels::channel_attachment_upload)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(channels::channel_attachment_download)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(channels::channel_attachment_description)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
	})
}
