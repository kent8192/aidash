//! Application endpoint registration and access policies.
use super::views::{channels, management, schedules, scratch};
use crate::apps::identity::services::boundary::AccessBoundary;
use reinhardt::UnifiedRouter;

pub fn url_patterns() -> UnifiedRouter {
	UnifiedRouter::new().server(|server| {
		server
			.endpoint(schedules::workspace_list)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(schedules::create)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(schedules::list)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(schedules::notices)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(schedules::limits)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(schedules::set_limits)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(schedules::read)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(schedules::update)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(schedules::pause)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(schedules::resume)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(schedules::successor)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(schedules::run_now)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(schedules::remove)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(scratch::create)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(scratch::list)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(scratch::limits)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(scratch::read)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(scratch::settings)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(scratch::add_member)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(scratch::remove_member)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(scratch::clear)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(scratch::remove)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(management::task_list)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(management::workspace_create)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(management::workspace_get)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(management::workspace_update)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(management::task_create)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(management::message_create)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(management::task_abandon)
			.with_route_middleware(
				AccessBoundary::authenticated()
					.with_visibility()
					.stops_work(),
			)
			.endpoint(management::conversation_create)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(channels::channel_thread_create)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(channels::channel_message_create)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(channels::channel_message_history)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(channels::channel_attachment_upload)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
			.endpoint(channels::channel_attachment_download)
			.with_route_middleware(AccessBoundary::authenticated().with_visibility())
	})
}
